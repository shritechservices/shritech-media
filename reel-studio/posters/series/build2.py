def render(p):
    if p['n'] not in (5, 22): p = deAI(p)
    img = gloss.base()
    gloss.glossy_art(img, ART[p['art']])
    header(img)
    gloss.greeting(img, p['title'], p.get('line2'))
    gloss.story_pill(img, p['pill'])
    DIAGRAMS[p['dg']](img, p['d'])
    if p.get('tone') == 'tribute':
        gloss.tribute_footer(img, p['foot'])
    else:
        aud, pr, so = PS[p['n']]
        gloss.ribbon2(img, aud, pr, so)
        gloss.cta(img, p['cta'])
    path = f"{OUT}/{p['n']:02d}-{p['date']}-{slug(p['occ'])}.jpg"
    finish3(img, path, f"{p['occ']} {p['date']} - Shri Tech")
    return path

