AI_SWAP = [('AI से डिज़ाइन', 'तुरंत डिज़ाइन'), ('AI बनाए रंगीन पोस्टर', 'बने रंगीन पोस्टर'), ('AI बनाए', 'तुरंत तैयार'),
           ('AI पोस्टर', 'तैयार पोस्टर'), ('AI कैप्शन', 'कैप्शन तैयार'), ('AI से तैयार', 'मिनटों में तैयार'),
           ('AI की मदद', 'स्मार्ट टूल'), ('AI लिखे', 'अपने-आप लिखे'), ('AI पोस्ट', 'पोस्ट तैयार'), ('AI से', 'मिनटों में')]

def deAI(o):
    if isinstance(o, str):
        for a, b in AI_SWAP: o = o.replace(a, b)
        return o
    if isinstance(o, (list, tuple)): return type(o)(deAI(x) for x in o)
    if isinstance(o, dict): return {k: deAI(v) for k, v in o.items()}
    return o

def slug(s): return re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')

def header(img):
    logo(img, M, 34, 44, dark=False)
    pw = tw('9993615146', 28, PB) + 92; xr = 1080 - M
    shadow(img, (xr - pw, 36, xr, 96), 30, blur=8, alpha=0.2, off=4, color=DEEP)
    gloss.grrect(img, (xr - pw, 36, xr, 96), 30, (22, 128, 61), (6, 46, 25), 0.25)
    phone_icon(img, xr - pw + 34, 66, 26, YEL)
